const ABBR_CAN_MAP: Record<string, string> = {
  'G.': 'Giáp',
  'Ấ.': 'Ất',
  'B.': 'Bính',
  'Đ.': 'Đinh',
  'M.': 'Mậu',
  'K.': 'Kỷ',
  'C.': 'Canh',
  'T.': 'Tân',
  'N.': 'Nhâm',
  'Q.': 'Quý',
};

export function translateCanChi(canChi?: string, lang: Language = 'vi'): string {
  if (!canChi) return '';
  if (lang === 'vi') return canChi;
  const trimmed = canChi.trim();
  const parts = trimmed.split(/\s+/);
  if (parts.length === 1) {
    const singleChi = CHI_TRANSLATIONS[parts[0]]?.[lang];
    if (singleChi) return singleChi;
    const singleCan = CAN_TRANSLATIONS[parts[0]]?.[lang];
    if (singleCan) return singleCan;
  }
  if (parts.length === 2) {
    const rawCan = ABBR_CAN_MAP[parts[0]] || parts[0];
    const chi = parts[1];
    const canTrans = CAN_TRANSLATIONS[rawCan]?.[lang];
    const chiTrans = CHI_TRANSLATIONS[chi]?.[lang];
    if (canTrans && chiTrans) {
      if (lang === 'zh' || lang === 'ja') return `${canTrans}${chiTrans}`;
      if (lang === 'ko') {
        const isAbbr = Boolean(ABBR_CAN_MAP[parts[0]]);
        return isAbbr
          ? `${canTrans}${chiTrans}`
          : `${canTrans}${chiTrans}(${CAN_TRANSLATIONS[rawCan]?.zh}${CHI_TRANSLATIONS[chi]?.zh})`;
      }
      if (lang === 'en') return `${canTrans} ${chiTrans}`;
    }
  }
  return canChi;
}

